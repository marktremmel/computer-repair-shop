#!/usr/bin/env bash
# Re-stamp index.html so browsers always pick up edited JS/CSS, and regenerate
# the offline data shims. Run after changing anything in js/ or css/.
cd "$(dirname "$0")"
python3 - <<'PY'
import re, json, hashlib, os

# ── offline shims ───────────────────────────────────────────────────────
# A school lab opening index.html straight off a USB stick has no origin, so
# fetch() on a local .json is blocked. These shims put the same data on the
# window instead. They are GENERATED, never hand-edited: a transcribed copy
# had already drifted from its source by one sprite, which is exactly the
# failure mode this loop exists to prevent.
SHIMS = [
    ('chipid-data.json',   'chipid-data.js',   'TechOpsChipData'),
    ('pixel-manifest.json', 'pixel-manifest.js', 'TechOpsPixelManifest'),
]
for src, dst, name in SHIMS:
    data = json.load(open(os.path.join('js', src)))
    body = json.dumps(data, ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    out = ('/* GENERATED by rebuild.sh from js/%s — do not edit by hand.\n'
           '   Lets the page work from file:// where fetch() has no origin. */\n'
           'window.%s = %s;\n') % (src, name, body)
    path = os.path.join('js', dst)
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != out:
        open(path, 'w', encoding='utf-8').write(out)
        print('regenerated js/%s' % dst)

# ── cache-busting stamp ─────────────────────────────────────────────────
stamp = hashlib.md5(b''.join(
    open(os.path.join(d, f), 'rb').read()
    for d in ('js', 'css') for f in sorted(os.listdir(d))
    if f.endswith(('.js', '.css', '.json'))
)).hexdigest()[:8]
s = open('index.html').read()
s = re.sub(r'(<script src="(?!http)[^"?]+)(\?v=[0-9a-f]+)?"', lambda m: m.group(1) + '?v=' + stamp + '"', s)
s = re.sub(r'(<link rel="stylesheet" href="(?!http)[^"?]+)(\?v=[0-9a-f]+)?"', lambda m: m.group(1) + '?v=' + stamp + '"', s)
s = re.sub(r'window\.TECHOPS_BUILD="[0-9a-f]*"', 'window.TECHOPS_BUILD="%s"' % stamp, s)
open('index.html', 'w').write(s)
print('build', stamp)
PY
